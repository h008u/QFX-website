/** أسئلة شائعة لكل رمز (تظهر في الصفحة وكبيانات FAQ منظّمة) */
export function marketFaqs(symbol: string, name: string): { q: string; a: string }[] {
  const g = MARKET_GUIDES[symbol];
  if (!g) return [];
  return [
    { q: `ما هي أفضل أوقات تداول ${name}؟`, a: g.sessions },
    { q: `ما الذي يحرك سعر ${symbol}؟`, a: g.drivers.join(" ") },
    { q: `كم تساوي النقطة في ${symbol}؟`, a: `${g.pip}. ${g.contract}. قيمة النقطة الفعلية تعتمد على حجم صفقتك ومواصفات الوسيط.` },
  ];
}
